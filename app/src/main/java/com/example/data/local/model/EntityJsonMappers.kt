package com.example.data.local.model

import org.json.JSONObject

fun Household.toJson(): String = JSONObject().apply {
    put("id", id)
    put("name", name)
    put("invite_code", inviteCode)
    put("created_by_user_id", createdByUserId)
    put("monthly_budget_limit", monthlyBudgetLimit)
    put("budget_warning_threshold", budgetWarningThreshold)
    put("created_at", createdAt)
}.toString()

